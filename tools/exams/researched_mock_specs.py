def section(
    index,
    family,
    title,
    filename,
    context,
    fields,
    background,
    unit,
    decision,
    points,
    source_ids,
    extra=None,
):
    questions = []
    for j, ((text, answer), point) in enumerate(zip(TASKS[family], points), 1):
        questions.append(
            dict(
                id="%d-%d" % (index, j),
                text=text,
                answer=answer,
                points=point,
                task=family + "_" + str(j),
            )
        )
    return dict(
        title=str(index) + ". " + title,
        data=filename,
        family=family,
        context=context,
        reader_guide=dict(
            background=background, unit=unit, decision=decision, fields=fields
        ),
        questions=questions,
        source_ids=source_ids,
        level="후기 유형 참고·조건/자료/배점은 창작"
        + ("·응용 확장" if not source_ids else ""),
        settings=extra or {},
    )


