def reading(folder, section, number=None):
    """배경·자료 사전·분석 목적을 계산 결과와 독립적으로 반환합니다."""
    if "reader_guide" in section:
        return dict(section["reader_guide"])
    data = section.get("data", "").split(" + ")
    rows = []
    if number:
        background, unit, decision = APPLIED[number - 1]
        filename = data[0]
        from applied_mock_specs import CASES

        if filename == "regression.csv":
            from applied_mock_specs import CASES

            features = CASES[number - 1][2]
            rows = [
                ("id", "관측 식별자; 예측 입력에서 제외"),
                ("target", CASES[number - 1][3] + "; 예측할 반응"),
            ] + [(f, FEATURE_NAMES[f] + "의 편차 지수; 원 측정값/표본 표준화 아님") for f in features]
        elif filename == "classification.csv":
            unit = "한 행은 회귀와 별도로 생성한 독립 사건 관측입니다."
            rows = [
                ("id", "관측 식별자"),
                ("target", "1=" + CASES[number - 1][4] + ", 0=해당 사건 없음"),
            ] + [("c" + str(i), "사건 전에 측정한 가상 연속 위험 신호 " + str(i)) for i in range(1, 5)]
            decision = (
                "실제 사건을 놓치는 경우와 잘못 경보하는 경우의 비용을 구분합니다."
            )
        else:
            unit = "한 행은 하루입니다. 앞 두 자료와 결합하지 않는 별도의 140일 합성 시계열입니다."
            rows = [
                ("date", "중복 없는 등간격 날짜"),
                (
                    "target",
                    "일별 수요/사용량의 학습용 연속 지표; 회귀·분류 target과 별개",
                ),
            ]
            decision = (
                "앞으로 7일의 값을 예측하고 단순 기준 예측과 같은 날짜에서 비교합니다."
            )
        return dict(background=background, unit=unit, decision=decision, fields=rows)
    background, unit = LEGACY.get(
        data[0],
        (
            "문서에서 관심 단어의 빈도와 날짜별 관심을 요약합니다.",
            "한 행은 문서 한 건입니다. 품사는 제공된 학습 사전의 표시에 한정됩니다.",
        ),
    )
    for name in data:
        mapping = FIELDS.get(
            name, {"date": "문서 작성 날짜", "text": "분석할 문서 내용"}
        )
        path = Path(folder) / "data" / name
        if path.exists():
            with path.open(newline="", encoding="utf-8-sig") as f:
                columns = next(csv.reader(f))
        else:
            columns = list(mapping)
        for column in columns:
            if column not in mapping:
                raise ValueError("변수 뜻 누락: " + name + "/" + column)
            rows.append((name + " / " + column, mapping[column]))
    return dict(
        background=background,
        unit=unit,
        decision="지문에서 요구한 비교·예측·요약의 결과와 불확실성을 상황에 맞게 보고합니다.",
        fields=rows,
    )


def markdown(guide):
    return "\n\n".join(
        [
            "**상황을 이해하기**\n\n" + guide["background"],
            "**관측 단위와 판단 목적**\n\n" + guide["unit"] + " " + guide["decision"],
            "**변수 사전**\n\n| 열 | 의미·역할 |\n| --- | --- |\n"
            + "\n".join(
                "| `" + name + "` | " + meaning + " |"
                for name, meaning in guide["fields"]
            ),
        ]
    )
